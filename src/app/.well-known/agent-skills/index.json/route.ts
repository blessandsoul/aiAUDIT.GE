import { createHash } from "node:crypto";
import { APP_DOMAIN, APP_NAME, SITE_CONTENT_UPDATED } from "../../../../lib/constants/app.constants";
import { GET as getCatalog } from "../../../ai/catalog.json/route";
import { GET as getFaq } from "../../../ai/faq.json/route";
import { GET as getService } from "../../../ai/service.json/route";
import { GET as getSummary } from "../../../ai/summary.json/route";
import { GET as getAiTxt } from "../../ai.txt/route";

export const revalidate = 86400;

function sha256(value: string): string {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

async function responseBytes(getter: () => Response | Promise<Response>): Promise<string> {
  const response = await getter();
  return response.text();
}

function resource(name: string, description: string, url: string, body: string) {
  return { name, type: "resource", description, url, sha256: sha256(body) };
}

export async function GET(): Promise<Response> {
  const baseUrl = `https://${APP_DOMAIN}`;
  const serviceBody = await responseBytes(getService);
  const catalogBody = await responseBytes(getCatalog);
  const faqBody = await responseBytes(getFaq);
  const summaryBody = await responseBytes(getSummary);
  const aiTxtBody = await responseBytes(getAiTxt);
  const resources = [
    resource(
      `${APP_NAME} Services Catalog`,
      `Current ${APP_NAME} services and implementation capabilities by aiNOW.`,
      `${baseUrl}/ai/service.json`,
      serviceBody,
    ),
    resource(
      `${APP_NAME} Product and Pricing Catalog`,
      `Current ${APP_NAME} product identities, prices, plan limits and pricing notes by aiNOW.`,
      `${baseUrl}/ai/catalog.json`,
      catalogBody,
    ),
    resource(
      `${APP_NAME} FAQ`,
      `Frequently asked questions about ${APP_NAME} scope, pricing, process and contact with aiNOW.`,
      `${baseUrl}/ai/faq.json`,
      faqBody,
    ),
    resource(
      `${APP_NAME} Company Profile`,
      `Public ${APP_NAME} profile, positioning, service languages, location and aiNOW ownership links.`,
      `${baseUrl}/ai/summary.json`,
      summaryBody,
    ),
    resource(
      `${APP_NAME} AI Crawler Policy`,
      `${APP_NAME} crawler access and aiNOW citation policy.`,
      `${baseUrl}/.well-known/ai.txt`,
      aiTxtBody,
    ),
  ];

  return new Response(
    `${JSON.stringify({
      "$schema": "https://www.agentskills.io/schemas/v0.2.0/index.json",
      version: "0.2.0",
      _meta: {
        publisher: APP_NAME,
        url: baseUrl,
        note: "Digests are calculated from the exact response bytes generated by this release.",
        lastUpdated: SITE_CONTENT_UPDATED,
      },
      skills: resources,
    }, null, 2)}\n`,
    {
      headers: {
        "Content-Type": "application/json; charset=utf-8",
        "Cache-Control": "public, max-age=86400, stale-while-revalidate=3600",
      },
    },
  );
}
